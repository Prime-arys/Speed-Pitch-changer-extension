/**
 * Builds `public/signalsmith-stretch-worklet.js` (run on postinstall).
 *
 * A worklet runs under the CSP of the page it is added to, and pages whose
 * `script-src` lacks 'wasm-unsafe-eval' (reddit, ...) refuse to compile
 * WebAssembly there. Nothing on the extension side can lift that for one script
 * only: a CSP has no way to allow a given wasm module (no hash support), the
 * content script compiles under the same policy on Chrome, and Firefox refuses
 * a compiled module handed over to the page.
 *
 * So the same module is also shipped translated to plain JS (wasm2js), and the
 * package's single `WebAssembly.instantiate()` call is hooked to fall back on it
 * when the browser refuses to compile the original.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const SOURCE = "node_modules/signalsmith-stretch/SignalsmithStretch.mjs";
const WASM2JS = "node_modules/binaryen/bin/wasm2js";
const OUTPUT = "public/signalsmith-stretch-worklet.js";

/** The call the hook replaces, and what it is replaced with. */
const INSTANTIATE = "WebAssembly.instantiate(binary,imports)";
const HOOK = "instantiateWithJsFallback";

/** Fails the install loudly when a new package version changes the layout. */
function expect(condition, message) {
    if (!condition) {
        throw new Error(`[signalsmith-worklet] ${message} (${SOURCE})`);
    }
}

const source = fs.readFileSync(SOURCE, "utf8");

const dataUri = source.match(/data:application\/octet-stream;base64,([A-Za-z0-9+/=]+)/);
expect(dataUri, "embedded wasm binary not found");
expect(source.split(INSTANTIATE).length === 2, `expected exactly one ${INSTANTIATE}`);
expect(!source.includes(HOOK), `${HOOK} already defined`);

// Translate the embedded module to JS.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "signalsmith-"));
let translated;
try {
    const wasmFile = path.join(tmp, "stretch.wasm");
    const jsFile = path.join(tmp, "stretch.js");
    fs.writeFileSync(wasmFile, Buffer.from(dataUri[1], "base64"));
    execFileSync(process.execPath, [WASM2JS, wasmFile, "-O3", "-o", jsFile]);
    translated = fs.readFileSync(jsFile, "utf8");
} finally {
    fs.rmSync(tmp, { recursive: true, force: true });
}

// wasm2js emits an ES module importing its imports and instantiating itself;
// keep only `asmFunc(imports)`, which returns the exports.
const importLine = "import * as a from 'a';\n";
const trailer = translated.indexOf("var retasmFunc");
expect(translated.startsWith(importLine) && trailer > 0, "unexpected wasm2js output");
const asmFunc = translated.slice(importLine.length, trailer);

const worklet = `// * Auto-generated by scripts/signalsmith-worklet.mjs, do not edit *

// The wasm module of signalsmith-stretch translated to JS by wasm2js.
const signalsmithStretchJs = (() => {
${asmFunc}
return asmFunc;
})();

// Pages whose CSP forbids WebAssembly make the compile below fail; run the JS
// translation of the same module instead (slower, same output).
function ${HOOK}(binary, imports) {
    return WebAssembly.instantiate(binary, imports).catch((error) => {
        if (!(error instanceof WebAssembly.CompileError)) throw error;
        return { instance: { exports: signalsmithStretchJs(imports) } };
    });
}

${source.replace(INSTANTIATE, `${HOOK}(binary,imports)`)}`;

fs.writeFileSync(OUTPUT, worklet);
console.log(`[signalsmith-worklet] ${OUTPUT} written`);
